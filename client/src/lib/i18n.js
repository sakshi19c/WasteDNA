// Names, types and notes that come from the database. Known demo values are
// translated; anything else (a ward a user adds) is shown as typed.
export function placeName(lang, name) {
  if (lang !== 'hi') return name
  const hit = T.hi.placeNames[name]
  if (hit) return hit
  const ward = /^Ward\s+(.+)$/i.exec(name)
  return ward ? `वार्ड ${ward[1]}` : name
}

export const placeType = (lang, type) => (lang === 'hi' ? T.hi.placeTypes[type] ?? type : type)

export const interventionText = (lang, text) => (lang === 'hi' ? T.hi.interventionText[text] ?? text : text)

export function assumptionText(lang, text) {
  const m = /^Estimated using a (\d+)% reduction in contamination\.$/.exec(text ?? '')
  if (lang === 'hi' && m) return `मिलावट में ${m[1]}% कमी मानकर अनुमान लगाया गया है।`
  if (lang === 'hi' && text === 'Projection based on synthetic demonstration data.') return 'अनुमान कृत्रिम (सिंथेटिक) डेमो डेटा पर आधारित है।'
  if (lang === 'hi' && text === 'Projection based on logged scans.') return 'अनुमान दर्ज किए गए स्कैन पर आधारित है।'
  return text
}

// Server errors carry a code. Known codes get a translated message; anything
// else (for example "No waste was found in this photo") shows the server text.
export const errorText = (lang, error) => T[lang].errors[error?.code] ?? error?.message ?? ''
